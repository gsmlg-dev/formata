-include_lib("eunit/include/eunit.hrl").

single_test_() ->
    ?_assertMatch(
      {formata_yaml_parser,
        string,
        [],
        <<>>,
        19,
        true,
        [],
        0,
        20,
        4,
        2,
        false,
        4,
        2,
        utf8,
        false,
        undefined,
        _,
        _,
        [],
        {bcoll,root,0,-1,1,1,-1,1,1},
        false,
        false,
        false,
        [{impl_key,false,false,undefined,undefined,1,1}],
        false,
        false,
        _,
        [],
        0,
        11,
        10,
        undefined,
        undefined,
        _,
        false,
        [],
        [
          {formata_yaml_stream_end,4,2},
          {formata_yaml_doc_end,4,2},
          {formata_yaml_collection_end,4,1,flow,sequence},
          {formata_yaml_scalar,3,3,
            {formata_yaml_tag,3,3,{non_specific,"?"}},
            flow,plain,"two"},
          {formata_yaml_sequence_entry,3,3},
          {formata_yaml_scalar,2,3,
            {formata_yaml_tag,2,3,{non_specific,"?"}},
            flow,plain,"one"},
          {formata_yaml_sequence_entry,2,3},
          {formata_yaml_collection_start,1,1,
            {formata_yaml_tag,1,1,{non_specific,"?"}},
            flow,sequence},
          {formata_yaml_doc_start,1,1,{1,2},_},
          {formata_yaml_stream_start,1,1,utf8}
